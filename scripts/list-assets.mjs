// Run with: npm run assets
// Writes ASSETS-TO-FIND.md: every image slot (figure block) in the guides, whether the file is in
// public/assets yet, and which topics have no videos.
import { existsSync, writeFileSync } from 'node:fs';
import { courses, topics, allUnits } from '../src/data/index.js';

const SECTIONS = { plain: 'In plain words', real: 'Real example', sports: 'Sports example' };
const figs = [];
for (const t of topics) {
  for (const [key, slides] of [['plain', t.plain], ['real', t.real.slides], ['sports', t.sports.slides]]) {
    slides.forEach((s, i) =>
      s.blocks.filter((b) => b.type === 'figure').forEach((b) => figs.push({ t, key, slide: i + 1, title: s.title, b })),
    );
  }
}
const have = (src) => src && existsSync(new URL(`../public/assets/${src}`, import.meta.url));
const courseTitle = (id) => courses.find((c) => c.id === id)?.short || id;

let md = '# Assets to find and add\n\n';
md += 'Generated by `npm run assets`. Put image files in `public/assets/` with the exact file name shown.\n';
md += 'Only use images you have the right to use (your own drawings or screenshots, free-licence images, or ones your instructor allows). Credit the source in the caption.\n\n';

md += `## 1. Images and diagrams (${figs.length} slots)\n\n`;
for (const course of courses) {
  const list = figs.filter((f) => f.t.course === course.id);
  if (!list.length) continue;
  md += `### ${course.title}\n\n`;
  md += '| Done | File name | Topic and slide | What to find or make |\n|---|---|---|---|\n';
  for (const f of list) {
    md += `| ${have(f.b.src) ? '✅' : '⬜'} | \`${f.b.src || '(no file name set)'}\` | ${f.t.title} · ${SECTIONS[f.key]} · slide ${f.slide} (“${f.title}”) | ${f.b.need.replace(/\|/g, '/')} |\n`;
  }
  md += '\n';
}

md += '## 2. Videos (YouTube or other)\n\n';
md += 'No video links are in the guides. For each topic, add 1 to 3 short videos in the topic file under `videos: [{ title, channel, url, length, note }]`. Suggested search words are given. Prefer short (under 12 minutes), clear explanations that match what your course slides say.\n\n';
md += '| Course | Topic | Suggested search |\n|---|---|---|\n';
for (const t of topics) {
  if ((t.videos || []).length === 0) md += `| ${courseTitle(t.course)} | ${t.title} | ${t.videoSearch || `${t.title} explained`} |\n`;
}

md += '\n## 3. Topics still waiting for course material\n\n';
for (const course of courses) {
  const missing = allUnits(course).filter((u) => !topics.some((t) => t.id === u.id));
  if (!missing.length) continue;
  md += `**${course.title}** (${missing.length}): ${missing.map((u) => u.title).join('; ')}\n\n`;
}
md += '## 4. Other things only you can supply\n\n';
md += '- Real examples marked with a source date need re-checking before the exam, because published figures change.\n';
md += '- Your own screenshots from the course platform or Excel (never include other students’ names or private grades).\n';
md += '- Any slide figure you want from your instructor’s decks: ask whether you may reuse it, or redraw it yourself.\n';
writeFileSync(new URL('../ASSETS-TO-FIND.md', import.meta.url), md);
console.log(`Wrote ASSETS-TO-FIND.md with ${figs.length} image slots.`);
